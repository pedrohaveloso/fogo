CREATE TABLE cities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  uf TEXT NOT NULL,
  ibge_code INTEGER NOT NULL UNIQUE,
  center_lat DOUBLE PRECISION NOT NULL,
  center_lng DOUBLE PRECISION NOT NULL,
  boundary JSONB NOT NULL,
  simulated BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE regions (
  id TEXT PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX regions_city ON regions (city_id);

CREATE TABLE neighborhoods (
  id TEXT PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  region_id TEXT NOT NULL REFERENCES regions (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  polygon JSONB NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  original_polygon JSONB,
  original_lat DOUBLE PRECISION,
  original_lng DOUBLE PRECISION,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX neighborhoods_city ON neighborhoods (city_id);

CREATE TABLE streets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  neighborhood_id TEXT NOT NULL REFERENCES neighborhoods (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  kind TEXT NOT NULL,
  cep TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL
);
CREATE INDEX streets_city ON streets (city_id);

CREATE TABLE pois (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  neighborhood_id TEXT NOT NULL REFERENCES neighborhoods (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  kind TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL
);
CREATE INDEX pois_city ON pois (city_id);

CREATE TABLE agencies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  UNIQUE (city_id, name)
);

CREATE TABLE equipment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id),
  type TEXT NOT NULL,
  serial_number TEXT NOT NULL UNIQUE,
  brand TEXT NOT NULL,
  model TEXT NOT NULL,
  agency_id INTEGER NOT NULL REFERENCES agencies (id),
  status TEXT NOT NULL,
  cep TEXT NOT NULL,
  street TEXT NOT NULL,
  reference TEXT NOT NULL,
  neighborhood_id TEXT NOT NULL REFERENCES neighborhoods (id),
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  current_lat DOUBLE PRECISION,
  current_lng DOUBLE PRECISION,
  maintenance_need TEXT NOT NULL,
  maintenance_interval_days INTEGER,
  last_maintenance_at TEXT,
  next_maintenance_at TEXT,
  maintenance_notes TEXT NOT NULL DEFAULT '',
  attributes JSONB NOT NULL DEFAULT '{}',
  installed_at TEXT,
  last_seen_at BIGINT,
  battery DOUBLE PRECISION,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX equipment_city ON equipment (city_id);
CREATE INDEX equipment_neighborhood ON equipment (neighborhood_id);

CREATE TABLE agents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id),
  name TEXT NOT NULL,
  badge TEXT NOT NULL,
  role TEXT NOT NULL,
  agency_id INTEGER NOT NULL REFERENCES agencies (id),
  rank TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  shift TEXT NOT NULL,
  status TEXT NOT NULL,
  base_name TEXT NOT NULL,
  base_neighborhood_id TEXT NOT NULL REFERENCES neighborhoods (id),
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  vehicle_id INTEGER REFERENCES equipment (id) ON DELETE SET NULL,
  occurrence_id INTEGER,
  last_seen_at BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (city_id, badge)
);
CREATE INDEX agents_city ON agents (city_id);

CREATE TABLE occurrences (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id INTEGER NOT NULL REFERENCES cities (id),
  kind TEXT NOT NULL,
  severity INTEGER NOT NULL,
  status TEXT NOT NULL,
  source TEXT NOT NULL,
  neighborhood_id TEXT NOT NULL REFERENCES neighborhoods (id),
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  description TEXT NOT NULL,
  equipment_id INTEGER REFERENCES equipment (id) ON DELETE SET NULL,
  agent_id INTEGER REFERENCES agents (id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  resolved_at BIGINT
);
CREATE INDEX occurrences_city_created ON occurrences (city_id, created_at);
CREATE INDEX occurrences_status ON occurrences (status);

CREATE TABLE equipment_status_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id INTEGER NOT NULL REFERENCES equipment (id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  at BIGINT NOT NULL
);
CREATE INDEX status_events_equipment ON equipment_status_events (equipment_id, at);

CREATE TABLE maintenance_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id INTEGER NOT NULL REFERENCES equipment (id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  at BIGINT NOT NULL
);
CREATE INDEX maintenance_events_equipment ON maintenance_events (equipment_id, at);

CREATE TABLE readings (
  equipment_id INTEGER NOT NULL REFERENCES equipment (id) ON DELETE CASCADE,
  hour_start BIGINT NOT NULL,
  count INTEGER NOT NULL,
  PRIMARY KEY (equipment_id, hour_start)
);
CREATE INDEX readings_hour ON readings (hour_start);

CREATE TABLE sim_flow_sites (
  equipment_id INTEGER PRIMARY KEY REFERENCES equipment (id) ON DELETE CASCADE,
  base_volume DOUBLE PRECISION NOT NULL
);

CREATE TABLE simulation_hours (
  hour_start BIGINT PRIMARY KEY
);

CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE tags (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL,
  equipment_id INTEGER UNIQUE REFERENCES equipment (id) ON DELETE CASCADE,
  agent_id INTEGER UNIQUE REFERENCES agents (id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  last_report_at BIGINT,
  CHECK ((equipment_id IS NULL) <> (agent_id IS NULL))
);

CREATE TABLE alert_acks (
  alert_id TEXT PRIMARY KEY,
  acknowledged_at BIGINT NOT NULL
);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL,
  city_id INTEGER REFERENCES cities (id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_username ON users (lower(username));

CREATE TABLE user_cities (
  user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  city_id INTEGER NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, city_id)
);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions (user_id);
